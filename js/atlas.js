export function discoveryAt(tile, chapter = 0) {
  const index = tile > 12 ? tile - 1 : tile;
  const [symbol, title, prompt] = atlasDiscoveries[(index + chapter * 7) % 24];
  return { symbol, title, prompt };
}
export function atlasMap(frame, interactive = false) {
  const p = frame.public,
    known = new Set(p.tiles.map((t) => t.tile));
  return `<section class="persistent-world atlas-world atlas-observations"><span class="eyebrow">ВАШИ МАЛЕНЬКИЕ ОТКРЫТИЯ · ГЛАВА ${p.chapter + 1}</span><h2>Атлас тихих открытий</h2><p>Посмотреть внимательнее. Обменяться находкой. Сохранить то, что хочется помнить.</p><div class="atlas-map">${Array.from(
    { length: 25 },
    (_, tile) => {
      const d =
        tile === 12
          ? { title: "Ваше место", symbol: "home" }
          : discoveryAt(tile, p.chapter);
      const tag = interactive && tile !== 12 ? "button" : "span";
      return `<${tag} class="atlas-tile ${known.has(tile) ? "known" : "nearby"} terrain-${tile % 4}" ${tag === "button" ? `data-world="atlas-place" data-tile="${tile}"` : ""} title="${esc(d.title)}" aria-label="${esc(d.title)}${known.has(tile) ? " · сохранено" : ""}">${icon(d.symbol)}<small>${esc(d.title)}${tile !== 12 && known.has(tile) ? " ✓" : ""}</small></${tag}>`;
    },
  ).join(
    "",
  )}</div><p class="atlas-count">${known.size - 1} / 24 мест с вашей историей · можно выбирать в любом порядке</p></section>`;
}
export function atlasNotebook(state, players, selected, interactive = true) {
  const notes = state.events.filter(
    (e) => e.type === "explore" && (selected == null || e.tile === selected),
  );
  return `<div class="atlas-journal">${
    notes
      .slice()
      .reverse()
      .map(
        (event) =>
          `<article><small>${esc(players.find((p) => p.id === event.author)?.name || "Ваш человек")} · ${new Date(event.at).toLocaleDateString("ru-RU")}</small><h3>${esc(discoveryAt(event.tile, state.chapter).title)}</h3><p>${esc(event.text || "Открытие из прежней версии атласа. Можно дополнить его своим воспоминанием.")}</p></article>`,
      )
      .join("") ||
    `<p class="muted">${interactive ? "Первые находки появятся здесь. Выберите место на карте — там маленькое приглашение заметить что-то хорошее." : "Пока вы выбираете первое открытие."}</p>`
  }</div>`;
}
