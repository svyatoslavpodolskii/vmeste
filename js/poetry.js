export function poetryOptions(round, turn, slot) {
  let seed = 2166136261;
  for (const char of `${round}:${turn}:${slot}`)
    seed = Math.imul(seed ^ char.charCodeAt(0), 16777619);
  const bank = banks[slot % 4];
  return Array.from(
    { length: 8 },
    (_, i) => bank[((seed >>> 0) + i * 5) % bank.length],
  );
}
export function poetryControls(frame, user, draft = {}) {
  const p = frame.public;
  return `<form id="party-answer-form" class="poetry-palette"><p>Выберите слова, которые вам сейчас откликаются. Чужие варианты скрыты — стих соберётся, когда все будут готовы.</p>${Array.from(
    { length: p.total },
    (_, i) => i,
  )
    .filter((i) => p.players[i % p.players.length].id === user)
    .map((slot) => {
      const options = poetryOptions(frame.round, p.turn || 0, slot);
      if (draft[slot] && !options.includes(draft[slot]))
        options.push(draft[slot]);
      return `<fieldset><legend>${["Наш пароль", "Какой у нас свет?", "Что будем делать?", "Где встретимся?"][slot % 4]}</legend><div class="poetry-words">${options.map((word) => `<label><input type="radio" name="${slot}" value="${esc(word)}" required ${draft[slot] === word ? "checked" : ""}><span>${esc(word)}</span></label>`).join("")}</div></fieldset>`;
    })
    .join(
      "",
    )}<button class="btn primary wide" type="submit">Мои слова готовы</button><p class="answer-note"></p></form>`;
}
